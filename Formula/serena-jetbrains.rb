# serena-jetbrains is the variant that uses the paid Serena JetBrains plugin as
# its code-intelligence backend, following the same pattern as
# Formula/rea-full.rb: it depends on Formula/serena.rb and installs
# `serena`/`serena-agent`/`serena-hooks` launchers that select that backend. It
# replaces the former scripts/setup-serena-jetbrains.py.
#
# The formula also installs `serena-jetbrains`, which installs the pinned
# IntelliJ IDEA Community Edition build and the plugin from this keg into the
# IDE's user plugins directory, under $SERENA_HOME/jetbrains by default. The IDE
# cannot be a dependency: it ships as a cask (and the last Apache-2.0 Community
# Edition is not in Homebrew at all), Homebrew formulae cannot depend on casks,
# and the IDE is only ever used as a hidden background code-intelligence
# backend, never as an editor. Everything the command downloads is pinned by URL
# and SHA-256 here, so no marketplace or release lookup happens at run time.
#
# Licensing: the formula text and the Serena application are GPL-3.0-or-later,
# but the bundled Serena plugin is a paid JetBrains Marketplace plugin. JetBrains
# loads it only with an active licence or its 7-day trial, tied to a JetBrains
# account; activation is a login in the IDE, so this formula cannot and does not
# bypass it. Without an activated plugin, run the plain `serena` formula (LSP
# backend) or `serena-full` until the plugin is activated.
#
# `serena`, `serena-full` and `serena-jetbrains` all provide `bin/serena`,
# `bin/serena-agent` and `bin/serena-hooks`: they are alternatives, not
# additions (see the caveats).
class SerenaJetbrains < Formula
  desc "Serena using the paid JetBrains plugin as its code-intelligence backend"
  homepage "https://github.com/oraios/serena"
  url "https://github.com/oraios/serena.git",
      tag:      "v2.1.0",
      revision: "5e4f5cd173c7ff3eed37ee3f1de6c266b937c5dc"
  # The formula text is GPL-3.0-or-later; the bundled plugin is proprietary.
  license :cannot_represent

  livecheck do
    url :homepage
    strategy :github_latest
  end

  depends_on arch: :arm64
  depends_on "fmu/tap/serena"

  # serena, serena-full and serena-jetbrains are alternatives that own the same
  # commands; whichever is installed last takes them over.
  link_overwrite "bin/serena", "bin/serena-agent", "bin/serena-hooks"

  # Serena JetBrains plugin 2023.3.5 (update 1167967) from the JetBrains
  # Marketplace: https://plugins.jetbrains.com/plugin/28946-serena/
  resource "plugin" do
    url "https://plugins.jetbrains.com/files/28946/1167967/serena-jetbrains-plugin-2023.3.5.zip"
    sha256 "19442ee1e1c8b7969b9300235824545dca76c786a8d88bad9709e95e0464417b"
  end

  def install
    prefix.install_metafiles
    # The marketplace archive holds one top-level directory; when it is the only
    # entry, `stage` changes into it instead of leaving it as a child.
    resource("plugin").stage do
      plugin_dir = Pathname.pwd.children.find { |child| child.basename.to_s == "serena-jetbrains-plugin" }
      staged_plugin = plugin_dir || Pathname.pwd
      libexec.install staged_plugin => "serena-jetbrains-plugin"
    end

    # The setup command. The IDE build below is the last Apache-2.0 IntelliJ
    # IDEA Community Edition; bump it together with its SHA-256 from
    # https://data.services.jetbrains.com/products/releases?code=IIC&type=release
    # when a newer Community build appears (2025.3 is the paid unified release).
    setup = <<~'PY'
      """Install the pinned IntelliJ IDEA CE build and the Serena JetBrains plugin.

      Generated by the fmu/tap serena-jetbrains formula. The plugin itself ships
      in this keg; only the IDE is downloaded, from the URL and SHA-256 pinned in
      the formula. Serena's launchers select the JetBrains backend, so this
      command does not edit the user's configuration.
      """

      import argparse
      import hashlib
      import json
      import os
      import shutil
      import subprocess
      import sys
      import time
      import urllib.request
      from pathlib import Path

      IDEA_VERSION = "2025.2.6.4"
      IDEA_BUILD = "252.28539.149"
      IDEA_URL = "https://download.jetbrains.com/idea/ideaIC-2025.2.6.4-aarch64.dmg"
      IDEA_SHA256 = "2c1810113f0fcfc1347ed93d22ae6666dc1c82ec16a94b987de8795f21e9659d"
      PLUGIN_VERSION = "2023.3.5"
      PLUGIN_NAME = "serena-jetbrains-plugin"
      APP_NAME = "IntelliJ IDEA CE.app"
      SERVER_PORT = 24226
      SERVER_PORTS = 20
      USER_AGENT = "fmu-tap-serena-jetbrains/1.0"
      HERE = Path(__file__).resolve().parent
      PLUGIN_SOURCE = HERE / PLUGIN_NAME


      class SetupError(Exception):
          """A setup step failed; the message is shown to the user."""


      def sha256_file(path):
          digest = hashlib.sha256()
          with path.open("rb") as handle:
              for chunk in iter(lambda: handle.read(1 << 20), b""):
                  digest.update(chunk)
          return digest.hexdigest()


      def serena_home(argument):
          home = argument or os.environ.get("SERENA_HOME") or (Path.home() / ".serena")
          return Path(home).expanduser().resolve()


      def download(url, destination, expected_sha256):
          if destination.is_file():
              if sha256_file(destination) == expected_sha256:
                  print(f"  using cached {destination.name}")
                  return destination
              destination.unlink()
          destination.parent.mkdir(parents=True, exist_ok=True)
          print(f"  downloading {destination.name} (about 1.2 GB) ...")
          request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
          part = destination.with_name(destination.name + ".part")
          try:
              with urllib.request.urlopen(request, timeout=300) as response, part.open("wb") as handle:
                  shutil.copyfileobj(response, handle, length=1 << 20)
          except OSError as error:
              part.unlink(missing_ok=True)
              raise SetupError(f"download of {url} failed: {error}") from error
          actual = sha256_file(part)
          if actual != expected_sha256:
              part.unlink(missing_ok=True)
              raise SetupError(f"checksum mismatch for {destination.name}: expected {expected_sha256}, got {actual}")
          os.replace(part, destination)
          return destination


      def check_free_space(path, required):
          path.mkdir(parents=True, exist_ok=True)
          free = shutil.disk_usage(path).free
          if free < required:
              raise SetupError(
                  f"not enough free disk space under {path}: "
                  f"{free / 1e9:.1f} GB free, about {required / 1e9:.1f} GB needed"
              )


      def read_product_info(app):
          product_info = app / "Contents" / "Resources" / "product-info.json"
          if not product_info.is_file():
              raise SetupError(f"{app} is not an IntelliJ IDEA installation")
          data = json.loads(product_info.read_text("utf-8"))
          for key in ("name", "version", "buildNumber", "dataDirectoryName"):
              if not data.get(key):
                  raise SetupError(f"{product_info} is missing the {key!r} field")
          return data


      def install_ide(base, force, keep_downloads):
          app = base / "apps" / APP_NAME
          if app.is_dir() and not force:
              try:
                  info = read_product_info(app)
              except (SetupError, ValueError):
                  info = None
              if info is not None and info["version"] == IDEA_VERSION:
                  print(f"  IntelliJ IDEA {info['version']} ({info['buildNumber']}) is already installed")
                  return app, info

          check_free_space(base, 5_000_000_000)
          dmg = download(IDEA_URL, base / "downloads" / Path(IDEA_URL).name, IDEA_SHA256)
          mount = base / "downloads" / "mnt"
          if mount.exists():
              shutil.rmtree(mount)
          mount.mkdir(parents=True)
          subprocess.run(
              ["hdiutil", "attach", "-nobrowse", "-readonly", "-mountpoint", str(mount), str(dmg)],
              check=True,
              capture_output=True,
          )
          try:
              candidates = sorted(mount.glob("*.app"))
              if len(candidates) != 1:
                  raise SetupError(f"expected one .app in {dmg.name}, found {[c.name for c in candidates]}")
              if app.exists():
                  shutil.rmtree(app)
              app.parent.mkdir(parents=True, exist_ok=True)
              subprocess.run(["ditto", str(candidates[0]), str(app)], check=True, capture_output=True)
          finally:
              subprocess.run(["hdiutil", "detach", str(mount)], check=False, capture_output=True)
              shutil.rmtree(mount, ignore_errors=True)
          subprocess.run(["xattr", "-dr", "com.apple.quarantine", str(app)], check=False, capture_output=True)
          if not keep_downloads:
              dmg.unlink(missing_ok=True)
          return app, read_product_info(app)


      def install_plugin(product_info):
          if not PLUGIN_SOURCE.is_dir():
              raise SetupError(f"the Serena plugin is missing from {PLUGIN_SOURCE}; reinstall the formula")
          plugins_dir = (
              Path.home() / "Library" / "Application Support" / "JetBrains" / product_info["dataDirectoryName"] / "plugins"
          )
          destination = plugins_dir / PLUGIN_NAME
          plugins_dir.mkdir(parents=True, exist_ok=True)
          if destination.exists():
              shutil.rmtree(destination)
          shutil.copytree(PLUGIN_SOURCE, destination)
          return destination


      def wait_for_plugin_server(timeout):
          deadline = time.monotonic() + timeout
          while time.monotonic() < deadline:
              for port in range(SERVER_PORT, SERVER_PORT + SERVER_PORTS):
                  try:
                      with urllib.request.urlopen(f"http://127.0.0.1:{port}/status", timeout=2) as response:
                          status = json.loads(response.read().decode("utf-8"))
                  except Exception:
                      continue
                  if isinstance(status, dict) and status.get("project_root"):
                      return port, status
              time.sleep(2)
          return None


      def launch_idea(app, project):
          subprocess.run(["open", "-g", "-j", "-a", str(app), str(project)], check=True)


      def main(argv=None):
          parser = argparse.ArgumentParser(
              description="Install the pinned IntelliJ IDEA Community Edition build and the Serena JetBrains "
              "plugin, as the backend the serena-jetbrains launchers select.",
              formatter_class=argparse.ArgumentDefaultsHelpFormatter,
          )
          parser.add_argument("--serena-home", type=Path, default=None,
                              help="Serena home directory (default: $SERENA_HOME or ~/.serena)")
          parser.add_argument("--force", action="store_true", help="reinstall the IDE and the plugin")
          parser.add_argument("--keep-downloads", action="store_true", help="keep the downloaded disk image")
          parser.add_argument("--dry-run", action="store_true", help="print the pinned assets without changing anything")
          parser.add_argument("--activate", action="store_true",
                              help="open the IDE for the one-time agreement and plugin trial/licence login")
          parser.add_argument("--verify", action="store_true",
                              help="launch the IDE for --project and wait for the plugin server")
          parser.add_argument("--project", type=Path, default=Path.cwd(), help="project directory used by --verify")
          parser.add_argument("--timeout", type=float, default=180.0, help="seconds to wait for the plugin server")
          args = parser.parse_args(argv)

          try:
              if sys.platform != "darwin":
                  raise SetupError("the Serena JetBrains backend is packaged for macOS only")
              base = serena_home(args.serena_home) / "jetbrains"

              if args.dry_run:
                  print("Serena JetBrains backend, pinned assets:")
                  print(f"  IntelliJ IDEA {IDEA_VERSION} ({IDEA_BUILD})")
                  print(f"    {IDEA_URL}")
                  print(f"    sha256 {IDEA_SHA256}")
                  print(f"  Serena plugin {PLUGIN_VERSION}")
                  print(f"    {PLUGIN_SOURCE}")
                  print(f"  installs under {base}")
                  return 0

              print("Serena JetBrains backend setup")
              print(f"  serena home: {base.parent}")
              print(f"  install dir: {base}")
              print("\n[1/2] IntelliJ IDEA Community Edition")
              app, product_info = install_ide(base, args.force, args.keep_downloads)
              print("\n[2/2] Serena JetBrains plugin")
              plugin_dir = install_plugin(product_info)

              print("\nInstalled")
              print(f"  IDE:    {product_info['name']} {product_info['version']} ({product_info['buildNumber']})")
              print(f"  app:    {app}")
              print(f"  plugin: {PLUGIN_VERSION} in {plugin_dir}")

              if args.activate:
                  print("\nOpening the IDE for the one-time steps:")
                  print("  1. accept the JetBrains end-user/data-sharing agreement")
                  print("  2. when the plugin asks for a licence, start the 7-day trial or activate a licence")
                  print("     (both are tied to your JetBrains account)")
                  print("  3. quit the IDE; the launchers start it hidden from now on")
                  subprocess.run(["open", "-a", str(app)], check=False)

              if args.verify:
                  project = args.project.expanduser().resolve()
                  print(f"\nVerifying: launching the IDE for {project} ...")
                  launch_idea(app, project)
                  result = wait_for_plugin_server(args.timeout)
                  if result is None:
                      print("The plugin server did not become reachable. Check:")
                      print("  * the JetBrains agreement was accepted (--activate)")
                      print("  * the paid plugin has an active licence or trial (--activate)")
                      print("  * the first project activation indexes the project and can take minutes")
                      return 2
                  port, status = result
                  print(f"  plugin server on port {port}: project_root={status.get('project_root')}")
                  print("  the JetBrains backend is reachable")

              print(
                  "\nNext steps (one-time):\n"
                  "  * run `serena-jetbrains --activate` if you have not accepted the JetBrains agreement\n"
                  "    and started the plugin's trial or activated a licence\n"
                  f"  * remove the backend again with: rm -rf {base}\n"
                  f"  * the plugin lives in {plugin_dir} and can be removed there too"
              )
              return 0
          except SetupError as error:
              print(f"error: {error}", file=sys.stderr)
              return 1


      if __name__ == "__main__":
          sys.exit(main())
    PY
    (libexec/"serena-jetbrains").write "#!#{formula_opt_libexec("serena")}/bin/python\n#{setup}"
    chmod 0755, libexec/"serena-jetbrains"
    bin.install_symlink libexec/"serena-jetbrains"

    # Serena's `jetbrains_launch_command`: open the installed IDE hidden and
    # return immediately (Serena polls the plugin's port itself).
    (libexec/"launch-idea").write <<~SH
      #!/bin/bash
      SERENA_HOME="${SERENA_HOME:-$HOME/.serena}"
      APP="$SERENA_HOME/jetbrains/apps/IntelliJ IDEA CE.app"
      if [ ! -d "$APP" ]; then
        echo "IntelliJ IDEA CE is not installed at $APP; run 'serena-jetbrains' first" >&2
        exit 1
      fi
      exec /usr/bin/open -g -j -a "$APP" "$@"
    SH
    chmod 0755, libexec/"launch-idea"

    # The variant launchers select the JetBrains backend and its launch command;
    # serena's parsed config merges them without editing the user's file.
    %w[serena serena-agent serena-hooks].each do |command|
      (bin/command).write <<~SH
        #!/bin/bash
        export SERENA_TAP_LANGUAGE_BACKEND="JetBrains"
        export SERENA_TAP_JETBRAINS_LAUNCH_COMMAND="#{opt_libexec}/launch-idea"
        exec "#{formula_opt_libexec("serena")}/bin/#{command}" "$@"
      SH
      (bin/command).chmod 0755
    end
  end

  def caveats
    <<~EOS
      This formula installs launchers for the JetBrains backend. Do the one-time
      setup first:

        serena-jetbrains              # install the pinned IDE and plugin
        serena-jetbrains --activate   # accept the agreement, start the plugin trial

      The IDE is installed under ~/.serena/jetbrains (override with SERENA_HOME)
      and is only ever started hidden; it is never used as an editor. The first
      project activation indexes the project and can take minutes.

      The Serena plugin is a paid JetBrains Marketplace plugin with a 7-day
      trial; JetBrains only loads it with an active licence or trial tied to your
      JetBrains account, which this formula cannot activate for you. Until it is
      activated, use the plain `serena` formula (LSP backend) or
      `fmu/tap/serena-full` (pinned OSS language servers).

      `serena`, `serena-full` and `serena-jetbrains` are alternatives, not
      additions: all provide `bin/serena`, `bin/serena-agent` and
      `bin/serena-hooks`, and installing one after the other replaces those
      commands (Homebrew reports the overwritten links). To use the plain CLI
      while this formula is installed:

        brew unlink serena && brew link serena

      Remove the backend again with:

        rm -rf ~/.serena/jetbrains
        rm -rf ~/Library/Application\\ Support/JetBrains/*/plugins/serena-jetbrains-plugin
    EOS
  end

  test do
    assert_match "Serena #{version}", shell_output("#{bin}/serena --version")
    assert_match "start-mcp-server", shell_output("#{bin}/serena --help")

    launcher = (bin/"serena").read
    assert_match "SERENA_TAP_LANGUAGE_BACKEND", launcher
    assert_match "SERENA_TAP_JETBRAINS_LAUNCH_COMMAND", launcher
    assert_match formula_opt_libexec("serena").to_s, launcher

    assert_path_exists libexec/"serena-jetbrains-plugin/lib"
    assert_path_exists libexec/"launch-idea"
    assert_predicate libexec/"serena-jetbrains", :executable?

    # The setup command must report the pinned assets without touching anything
    # or reaching the network.
    dry_run = shell_output("#{bin}/serena-jetbrains --dry-run")
    assert_match "IntelliJ IDEA 2025.2.6.4", dry_run
    assert_match "Serena plugin 2023.3.5", dry_run
    assert_match "serena-jetbrains-plugin", dry_run

    # The wrapper must point at the setup command instead of failing obscurely.
    error = shell_output("#{libexec}/launch-idea /tmp 2>&1", 1)
    assert_match "run 'serena-jetbrains' first", error

    # End to end: the launchers' environment selects the backend and launch
    # command in the serena keg's configuration.
    ENV["SERENA_HOME"] = (testpath/"home").to_s
    config_path = testpath/"home/serena_config.yml"
    system formula_opt_libexec("serena")/"bin/python", "-c", <<~PY
      from serena.config.serena_config import SerenaConfig
      from serena.language_backend import BuiltinLanguageBackend
      SerenaConfig.init(builtin_language_backend=BuiltinLanguageBackend.LSP)
    PY
    ENV["SERENA_TAP_LANGUAGE_BACKEND"] = "JetBrains"
    ENV["SERENA_TAP_JETBRAINS_LAUNCH_COMMAND"] = (opt_libexec/"launch-idea").to_s
    system formula_opt_libexec("serena")/"bin/python", "-c", <<~PY, config_path
      import sys
      from serena.config.serena_config import SerenaConfig
      config = SerenaConfig.from_config_file()
      assert config.language_backend.get_key() == "JetBrains", config.language_backend
      assert config.jetbrains_launch_command.endswith("/launch-idea"), config.jetbrains_launch_command
    PY
  end
end
